<?php
session_start();
include('../../inc/connection.php');
include('../../inc/gen_funcs.php');
require_once('../tot/funcs.php');
require_once(__DIR__ . '/render_css.php');

$receiptDivider = function_exists('kp_receipt_divider_text') ? kp_receipt_divider_text($connection) : str_repeat('*', 50);

$tot_id = (int)($_GET['id'] ?? $_GET['tot_id'] ?? ($_SESSION['tot'] ?? 0));
$auto_print = (int)($_GET['auto_print'] ?? 0) === 1;
$return_to = trim((string)($_GET['return_to'] ?? ''));
$session_user_id = (int)($_SESSION['user_id'] ?? 0);
if ($tot_id < 1) {
    exit('Invalid units slip');
}

$totHeader = mysqli_query($connection, "SELECT * FROM kp_tot WHERE tot_id='$tot_id' ORDER BY tot_id DESC LIMIT 1");
$tot = ($totHeader && mysqli_num_rows($totHeader) > 0) ? mysqli_fetch_assoc($totHeader) : null;
$user_id = $tot ? (int)$tot['user_id'] : $session_user_id;
$counter = $tot ? (int)$tot['counter'] : ($user_id > 0 ? (int)get_column('kp_users', 'counter', "user_id='$user_id'") : 0);
$shift = $tot ? (string)$tot['shift'] : (string)get_column('kp_shift', 'shift', "1");
$counter_name = $counter > 0 ? get_counter($counter) : 'UNIT GENERATOR';
$print_template = kp_render_print_template_id();
?>
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Units Generated #<?php echo $tot_id; ?></title>
  <style>
    <?php echo kp_render_print_template_css($print_template); ?>
    .receipt-divider { margin:0; line-height:1.1; white-space:nowrap; overflow:hidden; text-align:center; font-weight:700; letter-spacing:.06em; }
    body, #receipt, table, #receipt-header, #receipt-body, #receipt-footer {
      background: #fff !important;
    }
  </style>
</head>
<body>
<div id="receipt">
  <div id="bord">
    <div id="receipt-header" class="text-center">
      <p class="receipt-divider"><?php echo htmlspecialchars($receiptDivider); ?></p>
      <h1 style="margin:0;"><?php echo htmlspecialchars($counter_name); ?></h1>
      <p class="receipt-divider"><?php echo htmlspecialchars($receiptDivider); ?></p>
      <h2 style="margin:0;">UNITS GENERATED</h2>
      <p class="receipt-divider"><?php echo htmlspecialchars($receiptDivider); ?></p>
      <h2 style="margin:0;">GENERATED BY: <?php echo strtoupper(get_user($user_id)); ?></h2>
      <h2 style="margin:0;">Unit No: <?php echo $tot_id; ?></h2>
      <h2 style="margin:0;"><strong>SHIFT: <?php echo htmlspecialchars($shift); ?></strong></h2>
      <span><strong>PRINT TIME: <?php echo totime(); ?></strong></span>
      <p class="receipt-divider"><?php echo htmlspecialchars($receiptDivider); ?></p>
    </div>
    <div id="receipt-body">
      <table>
        <thead>
          <tr>
            <th>No.</th><th>Item</th><th>Units</th>
          </tr>
        </thead>
        <tbody>
          <?php
          $no = 0;
          $get_items = mysqli_query($connection, "SELECT * FROM kp_tot_items WHERE tot_id='$tot_id'");
          while ($s = mysqli_fetch_assoc($get_items)) {
              $no++;
              echo '<tr><td>' . $no . '</td><td>' . htmlspecialchars(get_item($s['tot_item_id'])) . '</td><td>' . htmlspecialchars($s['tots']) . '</td></tr>';
          }
          ?>
        </tbody>
      </table>
    </div>
    <p class="receipt-divider"><?php echo htmlspecialchars($receiptDivider); ?></p>
    <p class="receipt-divider"><?php echo htmlspecialchars($receiptDivider); ?></p>
    <br>
  </div>
</div>
<?php if ($auto_print): ?>
<script>
  window.addEventListener('load', function () {
    setTimeout(function () {
      window.print();
    }, 250);
  });
  <?php if ($return_to !== ''): ?>
  window.addEventListener('afterprint', function () {
    window.location.replace(<?php echo json_encode($return_to); ?>);
  });
  <?php endif; ?>
</script>
<?php endif; ?>
</body>
</html>
